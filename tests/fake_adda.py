"""Stand-in for the ADDA executable, used to test the subprocess plumbing.

It checks the command line the way ADDA would (shape file readable, enough -m
pairs for the domains used), then writes a log and a CrossSec file in the format
of the ADDA manual (§C.4, §C.7) with made-up numbers the tests can predict:

    Cext = size * lambda,   Cabs = number of dipoles,   no Csca.
"""

import sys
from pathlib import Path


def main(argv):
    if argv[:1] == ["-V"]:
        print("ADDA v.9.9.9-fake\nfake build for lightsmith-adda tests")
        return 0
    args = {}
    i = 0
    while i < len(argv):
        key = argv[i]
        j = i + 1
        while j < len(argv) and not (argv[j].startswith("-") and not _is_number(argv[j])):
            j += 1
        args[key] = argv[i + 1:j]
        i = j
    assert args["-shape"][0] == "read", args
    rows, nmat = [], None
    for line in Path(args["-shape"][1]).read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        if line.startswith("Nmat="):
            nmat = int(line[5:])
            continue
        rows.append([int(v) for v in line.split()])
    domains = {r[3] if len(r) == 4 else 1 for r in rows}
    m = [float(v) for v in args["-m"]]
    if len(m) % 2 or len(m) // 2 < max(domains):
        print(f"ERROR: {len(m) // 2} refractive indices given for {max(domains)} domains", file=sys.stderr)
        return 1
    if nmat is not None and nmat != max(domains):
        print("WARNING: Nmat differs from the maximum domain number", file=sys.stderr)
    size, lam = float(args["-size"][0]), float(args["-lambda"][0])
    box_x = max(r[0] for r in rows) - min(r[0] for r in rows) + 1
    out = Path(args["-dir"][0])
    out.mkdir(parents=True, exist_ok=True)
    cmdline = " ".join(argv)
    (out / "log").write_text(
        f"Generated by ADDA v.9.9.9-fake\ncommand: 'adda {cmdline} '\nlambda: {lam}\n"
        f"Dipole size: {size / box_x:.6g} (cubical)\nTotal number of occupied dipoles: {len(rows)}\n"
        "Polarizability relation: 'Lattice Dispersion Relation'\nIterative Method: QMR (complex symmetric)\n"
        "Total number of iterations: 7\n")
    name = "CrossSec" if "-orient" in args and args["-orient"][:1] == ["avg"] else "CrossSec-Y"
    (out / name).write_text(f"Cext\t= {size * lam:.10g}\nQext\t= 1\nCabs\t= {len(rows):.10g}\nQabs\t= 1\n")
    return 0


def _is_number(s):
    try:
        float(s)
        return True
    except ValueError:
        return False


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
